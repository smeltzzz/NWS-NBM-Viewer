'use client';

/**
 * Comprehensive NBM product catalog for the workstation UI.
 * Organized into 7 operational categories mirroring AWIPS II / Pivotal Weather.
 *
 * Each product maps to a backend element code, colormap, and supported sub-selectors.
 */

export type ProductType = 'deterministic' | 'mean' | 'probabilistic';
export type Accumulation = '1h' | '6h' | '12h' | '24h' | '48h' | '72h';
export type Percentile = 10 | 25 | 50 | 75 | 90 | 95;

export type CategoryId =
  | 'temp_moisture'
  | 'precip_qpf'
  | 'winter'
  | 'wind'
  | 'convective'
  | 'aviation_marine'
  | 'fire';

export interface NBMProductDef {
  id: string;
  element: string; // backend element key
  label: string;
  shortLabel: string;
  description: string;
  category: CategoryId;
  colormap: string; // key into COLOUR_MAPS
  units: {
    native: string;
    imperial: string;
    metric: string;
  };
  types: ProductType[];
  defaultType: ProductType;
  accumulations?: Accumulation[];
  defaultAccum?: Accumulation;
  percentiles?: Percentile[];
  defaultPercentile?: Percentile;
  thresholds?: string[]; // display labels like "≥ 0.10\""
  thresholdValues?: number[]; // native values mm or m/s or degC
  searchable: string[]; // keywords for fuzzy search
  isFavoriteDefault?: boolean;
  versionNote?: string; // e.g., "NBM v4.2"
}

export interface CategoryDef {
  id: CategoryId;
  label: string;
  icon: string;
  description: string;
  products: NBMProductDef[];
}

