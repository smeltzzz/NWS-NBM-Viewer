// ── Helpers ─────────────────────────────────────────────────────────────────
export function allProducts(): NBMProductDef[] {
  return CATEGORIES.flatMap(c => c.products);
}

export function getProductById(id: string): NBMProductDef | undefined {
  return allProducts().find(p => p.id === id);
}

export function getProductByElement(element: string): NBMProductDef | undefined {
  return allProducts().find(p => p.element === element);
}

export function searchProducts(query: string): NBMProductDef[] {
  if (!query.trim()) return allProducts();
  const q = query.toLowerCase().trim();
  // fuzzy: split into tokens, all tokens must be present in searchable or label
  const tokens = q.split(/\s+/);
  return allProducts().filter(p => {
    const haystack = [
      p.label.toLowerCase(),
      p.shortLabel.toLowerCase(),
      p.description.toLowerCase(),
      p.element.toLowerCase(),
      p.id.toLowerCase(),
      ...p.searchable.map(s => s.toLowerCase()),
    ].join(' ');
    return tokens.every(tok => haystack.includes(tok));
  });
}

export function getCategoryById(id: CategoryId): CategoryDef | undefined {
  return CATEGORIES.find(c => c.id === id);
}
